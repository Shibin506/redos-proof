#!/usr/bin/env bash
# Regenerates src/tables.rs: the exact character classes of each engine, found by asking the engine itself
# about every code point (so the tables are what the engine does, not what a document says it does).
set -euo pipefail
cd "$(dirname "$0")/.."
out=src/tables.rs
ranges() { # reads code points (one per line), prints Rust ranges
  python3 -c '
import sys
cps = [int(l) for l in sys.stdin if l.strip()]
out, lo, hi = [], None, None
for c in cps:
    if lo is None: lo = hi = c
    elif c == hi + 1: hi = c
    else: out.append((lo, hi)); lo = hi = c
if lo is not None: out.append((lo, hi))
print(", ".join(f"(0x{a:X}, 0x{b:X})" for a, b in out))'
}
py() { python3 -c "
import re, sys
r = re.compile(r'$1')
for c in range(0x110000):
    if 0xD800 <= c <= 0xDFFF: continue
    if r.match(chr(c)): print(c)" | ranges; }
rb() { LANG=C.UTF-8 ruby -Ku -e "
r = Regexp.new('\\\\A$1\\\\z')
(0...0x110000).each { |c| next if (0xD800..0xDFFF).cover?(c); puts c if r.match?(c.chr(Encoding::UTF_8)) }" | ranges; }
js() { node -e "
const r = /^$1\$/u; const out = [];
for (let c = 0; c < 0x110000; c++) { if (c >= 0xD800 && c <= 0xDFFF) continue; if (r.test(String.fromCodePoint(c))) out.push(c); }
console.log(out.join('\n'))" | ranges; }
{
  echo "//! Generated by script/gen_tables.sh from $(python3 --version), Ruby $(ruby -e 'print RUBY_VERSION') and Node $(node --version). Do not edit."
  echo "//! Each table is exactly the set of code points the engine itself matches with that class."
  echo
  echo "pub const PY_WORD: &[(u32, u32)] = &[$(py '\w')];"
  echo "pub const PY_DIGIT: &[(u32, u32)] = &[$(py '\d')];"
  echo "pub const PY_SPACE: &[(u32, u32)] = &[$(py '\s')];"
  echo "pub const JS_SPACE: &[(u32, u32)] = &[$(js '\s')];"
  # What Ruby's \b treats as a word character: asked of \b itself (\b at the start holds before a word character).
  echo "pub const RB_BOUNDARY_WORD: &[(u32, u32)] = &[$(LANG=C.UTF-8 ruby -Ku -e '(0...0x110000).each { |c| next if (0xD800..0xDFFF).cover?(c); puts c if /\A\b/.match?(c.chr(Encoding::UTF_8)) }' | ranges)];"
  for cls in alpha alnum digit upper lower space punct word xdigit cntrl graph print blank; do
    name=$(echo "$cls" | tr a-z A-Z)
    echo "pub const RB_POSIX_$name: &[(u32, u32)] = &[$(rb "[[:$cls:]]")];"
  done
} > "$out.tmp"
mv "$out.tmp" "$out"
wc -c "$out"
