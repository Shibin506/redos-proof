#!/usr/bin/env python3
"""Generates src/folds.rs: which characters each engine treats as the same letter under case-insensitive matching.

Candidates are grouped roughly (by Python's lower/upper/casefold, merged), then every pair inside a group is
tested in the real engine (`/^x$/i` against `y`). The table is the engines' answers, not a reading of a spec.
Only single-character folding is covered (Ruby's ß = ss is out of scope)."""
import json, subprocess, sys, unicodedata

def cased(c):
    ch = chr(c)
    return ch.lower() != ch or ch.upper() != ch or ch.casefold() != ch or ch.title() != ch

cands = [c for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF and cased(c)]
parent = {}
def find(x):
    parent.setdefault(x, x)
    while parent[x] != x:
        parent[x] = parent[parent[x]]
        x = parent[x]
    return x
def union(a, b):
    parent[find(a)] = find(b)
for c in cands:
    ch = chr(c)
    for m in (ch.lower(), ch.upper(), ch.casefold(), ch.title()):
        if len(m) == 1:
            union(c, ord(m))
groups = {}
for c in list(parent):
    groups.setdefault(find(c), []).append(c)
rough = [sorted(g) for g in groups.values() if len(g) > 1]
pairs = [[a, b] for g in rough for a in g for b in g if a != b]

ENGINES = {
    "JS_LEGACY": ["node", "-e", """
const pairs = JSON.parse(require('fs').readFileSync(0, 'utf8'));
const esc = c => c <= 0xFFFF ? '\\\\u' + c.toString(16).padStart(4, '0') : null;
const out = pairs.filter(([a, b]) => a <= 0xFFFF && b <= 0xFFFF && new RegExp('^' + esc(a) + '$', 'i').test(String.fromCharCode(b)));
console.log(JSON.stringify(out));"""],
    "JS_UNICODE": ["node", "-e", """
const pairs = JSON.parse(require('fs').readFileSync(0, 'utf8'));
const out = pairs.filter(([a, b]) => new RegExp('^\\\\u{' + a.toString(16) + '}$', 'iu').test(String.fromCodePoint(b)));
console.log(JSON.stringify(out));"""],
    "PY": [sys.executable, "-c", """
import json, re, sys
pairs = json.load(sys.stdin)
print(json.dumps([[a, b] for a, b in pairs if re.match('^\\\\U%08x$' % a, chr(b), re.I)]))"""],
    "RB": ["ruby", "-Ku", "-rjson", "-e", """
pairs = JSON.parse($stdin.read)
puts JSON.generate(pairs.select { |a, b| Regexp.new("\\\\A\\\\u{#{a.to_s(16)}}\\\\z", Regexp::IGNORECASE).match?(b.chr(Encoding::UTF_8)) })"""],
}

def components(edges):
    parent.clear()
    for a, b in edges:
        union(a, b)
    comps = {}
    for c in list(parent):
        comps.setdefault(find(c), []).append(c)
    return sorted(sorted(g) for g in comps.values() if len(g) > 1)

print(f"//! Generated by script/gen_folds.py ({len(pairs)} character pairs tested in each engine). Do not edit.")
print("//! Each group is a set of characters the engine treats as the same letter under case-insensitive matching.")
print()
for name, cmd in ENGINES.items():
    r = subprocess.run(cmd, input=json.dumps(pairs), capture_output=True, text=True, env={"LANG": "C.UTF-8", "PATH": __import__("os").environ["PATH"]})
    if r.returncode != 0:
        sys.exit(f"{name}: {r.stderr}")
    comps = components(json.loads(r.stdout))
    body = ", ".join("&[" + ", ".join(f"0x{c:X}" for c in g) + "]" for g in comps)
    print(f"pub const FOLD_{name}: &[&[u32]] = &[{body}];")
